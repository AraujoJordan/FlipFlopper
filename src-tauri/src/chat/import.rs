/// Convert each requested session and add it to the sidebar. Sessions that fail
/// to read or have no conversation are skipped.
pub fn import(requests: Vec<ImportRequest>) -> Vec<SessionMeta> {
    let mut imported = Vec::new();
    for req in requests {
        let path = PathBuf::from(&req.path);
        let converted = match req.agent_id.as_str() {
            "claude" => convert_claude(&path),
            "codex" => convert_codex(&path),
            _ => None,
        };
        let Some((entries, first_ts, last_ts)) = converted else { continue };
        let id = Uuid::new_v4().to_string();
        let count = entries.len();
        if store::write_entries(&id, &entries).is_err() {
            continue;
        }
        let created = if first_ts > 0 { first_ts } else { req.updated_at };
        let updated = if req.updated_at > 0 { req.updated_at } else { last_ts };
        let meta = SessionMeta {
            id: id.clone(),
            project_path: req.cwd.clone(),
            cwd: req.cwd,
            worktree: None,
            title: req.title,
            title_locked: false,
            agent_id: req.agent_id.clone(),
            model: None,
            effort: None,
            mode: PermissionMode::AutoEdit,
            yolo: false,
            native_ids: HashMap::from([(req.agent_id.clone(), req.native_id)]),
            acp_sessions: HashMap::new(),
            agent_last_entry: HashMap::from([(req.agent_id, count)]),
            entry_count: count,
            status: "idle".into(),
            archived: false,
            pinned: false,
            parent_id: None,
            created_at: created,
            updated_at: updated,
        };
        if store::insert_session(meta.clone()).is_ok() {
            imported.push(meta);
        }
    }
    imported
}

