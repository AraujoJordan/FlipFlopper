/// `2026-10-22T09:00:00.123Z` → epoch milliseconds. `None` on anything else.
pub(crate) fn parse_iso_ms(s: &str) -> Option<u64> {
    let b = s.as_bytes();
    if b.len() < 19 || b[4] != b'-' || b[7] != b'-' || (b[10] != b'T' && b[10] != b' ') {
        return None;
    }
    let num = |a: usize, z: usize| s.get(a..z)?.parse::<i64>().ok();
    let (y, m, d) = (num(0, 4)?, num(5, 7)?, num(8, 10)?);
    let (h, mi, sec) = (num(11, 13)?, num(14, 16)?, num(17, 19)?);
    let mut ms = 0i64;
    if b.len() > 20 && b[19] == b'.' {
        let digits: String = s[20..].chars().take_while(|c| c.is_ascii_digit()).take(3).collect();
        ms = format!("{digits:0<3}").parse().ok()?;
    }
    let yy = if m <= 2 { y - 1 } else { y };
    let era = (if yy >= 0 { yy } else { yy - 399 }) / 400;
    let yoe = yy - era * 400;
    let doy = (153 * (m + if m > 2 { -3 } else { 9 }) + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    let days = era * 146_097 + doe - 719_468;
    let total = ((days * 24 + h) * 60 + mi) * 60 + sec;
    u64::try_from(total * 1000 + ms).ok()
}

fn mtime_ms(path: &Path) -> u64 {
    fs::metadata(path)
        .and_then(|m| m.modified())
        .ok()
        .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

fn home() -> Option<PathBuf> {
    dirs::home_dir()
}

fn lines_of(path: &Path) -> Option<impl Iterator<Item = String>> {
    let file = File::open(path).ok()?;
    Some(BufReader::new(file).lines().map_while(Result::ok))
}

/// Cheap stability check for append-only CLI history. A live CLI may append
/// while Chat reads it; retry that sync instead of advancing past a line that
/// was only half written.
fn file_stamp(path: &Path) -> Option<(u64, Option<std::time::SystemTime>)> {
    let metadata = fs::metadata(path).ok()?;
    Some((metadata.len(), metadata.modified().ok()))
}

/// Claude encodes a project path as every non-alphanumeric char → `-`.
fn claude_encode_path(path: &str) -> String {
    path.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '-' }).collect()
}

/// Text of a message `content` (string, or the `text`/`input_text`/`output_text` parts).
fn content_texts(content: &Value) -> Vec<String> {
    match content {
        Value::String(s) => vec![s.clone()],
        Value::Array(parts) => parts
            .iter()
            .filter(|p| matches!(p.get("type").and_then(Value::as_str), Some("text" | "input_text" | "output_text")))
            .filter_map(|p| p.get("text").and_then(Value::as_str).map(str::to_string))
            .collect(),
        _ => Vec::new(),
    }
}

/// Text the CLIs inject into the conversation that the user never typed.
fn is_injected(text: &str) -> bool {
    let t = text.trim_start();
    t.is_empty()
        || t.starts_with("<command-")
        || t.starts_with("<local-command")
        || t.starts_with("<system-reminder>")
        || t.starts_with("<environment_context>")
        || t.starts_with("<user_instructions>")
        || t.starts_with("<permissions")
        || t.starts_with("<user_action>")
        || t.starts_with("# AGENTS.md instructions")
        || t.starts_with("Caveat: The messages below were generated by the user while running local commands")
        || t.starts_with("[Request interrupted by user")
}

/// The user-visible prompt in a message text, if any. Slash commands that
/// carry arguments (`/plan <text>`) become `/plan <text>`; bare commands, their
/// output and injected context yield `None`.
fn user_text(text: &str) -> Option<String> {
    let t = text.trim();
    if let Some(rest) = t.strip_prefix("<command-name>") {
        let (name, rest) = rest.split_once("</command-name>")?;
        let args = rest
            .split_once("<command-args>")
            .and_then(|(_, a)| a.split_once("</command-args>"))
            .map(|(a, _)| a.trim())
            .unwrap_or("");
        return (!args.is_empty()).then(|| format!("{} {}", name.trim(), args));
    }
    (!is_injected(t)).then(|| t.to_string())
}

