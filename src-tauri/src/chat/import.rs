    #[test]
    fn final_trim_preserves_one_oversized_turn() {
        let mut b = Builder::new("claude");
        b.user("keep this prompt".into(), 1);
        for _ in 0..=MAX_ENTRIES {
            b.event(ChatEvent::Text { delta: "large turn".into() }, 2);
        }
        let (entries, _, _) = b.finish();
        assert!(entries.len() > MAX_ENTRIES);
        assert!(matches!(&entries[0], Entry::User { text, .. } if text == "keep this prompt"));
        assert!(matches!(entries.last(), Some(Entry::Event { event: ChatEvent::TurnEnded { .. }, .. })));

        let mut b = Builder::new("claude");
        b.user("old oversized turn".into(), 1);
        for _ in 0..=MAX_ENTRIES {
            b.event(ChatEvent::Text { delta: "large turn".into() }, 2);
        }
        b.user("newest prompt".into(), 3);
        assert_eq!(b.entries.len(), 1);
        assert!(matches!(&b.entries[0], Entry::User { text, .. } if text == "newest prompt"));
    }

    /// Creates a real Claude session in a temp repo, imports it, then continues
    /// the imported session through the engine: Claude must still remember.
    /// Needs `claude` logged in; costs a few cents.
    /// `cargo test --lib imported_session_resumes -- --ignored --nocapture`
    #[test]
    #[ignore]
    fn imported_session_resumes() {
        use crate::chat::{ChatManager, Emitter, SendArgs};
        use std::process::Command;
        use std::sync::{mpsc, Arc, Mutex};
        use std::time::Duration;

        let data = std::env::temp_dir().join(format!("ff-imp-data-{}", Uuid::new_v4()));
        std::env::set_var("FLIPFLOPPER_DATA_DIR", &data);
        let repo = std::env::temp_dir().join(format!("ff-imp-repo-{}", Uuid::new_v4()));
        fs::create_dir_all(&repo).unwrap();
        let repo = repo.canonicalize().unwrap();
        let path = repo.to_str().unwrap().to_string();

        // 1. A real CLI session, outside FlipFlopper.
        let out = Command::new("claude")
            .args(["-p", "Remember the secret word PINEAPPLE. Reply ok."])
            .current_dir(&repo)
            .env("PATH", crate::env::augmented_path_string())
            .stdin(std::process::Stdio::null())
            .output()
            .expect("claude not runnable");
        assert!(out.status.success(), "claude failed: {}", String::from_utf8_lossy(&out.stderr));

        // 2. Scan finds it; import converts it.
        let found = scan(&[path.clone()]);
        let cand = found.iter().find(|c| c.agent_id == "claude").expect("session not discovered");
        let imported = import(vec![ImportRequest {
            agent_id: cand.agent_id.clone(),
            native_id: cand.native_id.clone(),
            path: cand.path.clone(),
            cwd: cand.cwd.clone(),
            title: cand.title.clone(),
            updated_at: cand.updated_at,
        }]);
        assert_eq!(imported.len(), 1);
        let meta = &imported[0];
        let entries = store::load_entries(&meta.id);
        assert!(entries.iter().any(|e| matches!(e, Entry::User { text, .. } if text.contains("PINEAPPLE"))), "{entries:?}");
        // Already-imported sessions are no longer offered.
        assert!(scan(&[path.clone()]).iter().all(|c| c.native_id != cand.native_id));

        // 3. Continue it: the resumed CLI session still knows the word.
        let (tx, rx) = mpsc::channel::<Entry>();
        let tx = Mutex::new(tx);
        let emit: Emitter = Arc::new(move |_s, e| { let _ = tx.lock().unwrap().send(e.clone()); });
        let manager = Arc::new(ChatManager::default());
        manager
            .send(emit, SendArgs {
                recover_context: false, session_id: meta.id.clone(),
                prompt: "What was the secret word? Answer with only the word.".into(),
                agent_id: "claude".into(),
                model: None,
                effort: None,
                mode: PermissionMode::Plan,
                yolo: false,
                context_from: None,
                attachments: vec![],
            })
            .unwrap();
        let mut text = String::new();
        loop {
            match rx.recv_timeout(Duration::from_secs(180)).expect("turn timed out") {
                Entry::Event { event: ChatEvent::Text { delta }, .. } => text.push_str(&delta),
                Entry::Event { event: ChatEvent::TurnEnded { .. }, .. } => break,
                _ => {}
            }
        }
        assert!(text.to_uppercase().contains("PINEAPPLE"), "imported session lost context: {text}");
        let _ = fs::remove_dir_all(&repo);
        let _ = fs::remove_dir_all(&data);
    }

    /// Against this machine's real session stores; reports what it finds.
    /// `FF_IMPORT_PROJECTS=/path cargo test --lib import_real_sessions -- --ignored --nocapture`
    #[test]
    #[ignore]
    fn import_real_sessions() {
        // `FF_IMPORT_PROJECTS=/a:/b` picks projects; default is this repository.
        let projects: Vec<String> = std::env::var("FF_IMPORT_PROJECTS")
            .map(|v| v.split(':').map(String::from).collect())
            .unwrap_or_else(|_| vec![std::env::current_dir().unwrap().parent().unwrap().to_string_lossy().to_string()]);
        let found = scan(&projects);
        println!("found {} candidates for {projects:?}", found.len());
        for c in found.iter().take(5) {
            println!("  {} {} {:>9}b {}", c.agent_id, c.native_id, c.size, c.title);
            let converted = match c.agent_id.as_str() {
                "claude" => convert_claude(Path::new(&c.path)),
                _ => convert_codex(Path::new(&c.path)),
            };
            let (entries, ..) = converted.expect("conversion failed");
            println!("    -> {} entries", entries.len());
            assert!(entries.iter().any(|e| matches!(e, Entry::User { .. })));
        }
    }
