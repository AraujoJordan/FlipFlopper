    fn write_tmp(name: &str, lines: &[&str]) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("ff-import-{}", Uuid::new_v4()));
        fs::create_dir_all(&dir).unwrap();
        let p = dir.join(name);
        fs::write(&p, lines.join("\n")).unwrap();
        p
    }

    #[test]
    fn slash_commands_with_args_become_prompts() {
        assert_eq!(
            user_text("<command-name>/plan</command-name>\n <command-message>plan</command-message>\n <command-args>Refactor the store</command-args>").as_deref(),
            Some("/plan Refactor the store")
        );
        assert_eq!(user_text("<command-name>/model</command-name><command-args></command-args>"), None);
        assert_eq!(user_text("<local-command-stdout>ok</local-command-stdout>"), None);
        assert_eq!(user_text("  just a prompt  ").as_deref(), Some("just a prompt"));
    }

    #[test]
    fn parses_iso_timestamps() {
        assert_eq!(parse_iso_ms("1970-01-01T00:00:00Z"), Some(0));
        assert_eq!(parse_iso_ms("2026-10-22T09:00:00.123Z"), Some(1_792_659_600_123));
        assert_eq!(parse_iso_ms("garbage"), None);
    }

    #[test]
