/// Find importable sessions whose working directory is one of `projects`,
/// skipping those whose native id is already attached to an existing session.
pub fn scan(projects: &[String]) -> Vec<ImportCandidate> {
    let wanted: HashSet<&str> = projects.iter().map(String::as_str).collect();
    let already: HashSet<(String, String)> = store::list_sessions()
        .into_iter()
        .flat_map(|s| s.native_ids.into_iter().collect::<Vec<_>>())
        .collect();

    let mut out = Vec::new();
    out.extend(scan_claude(projects));
    out.extend(scan_codex(&wanted));
    out.retain(|c| !already.contains(&(c.agent_id.clone(), c.native_id.clone())));
    out.sort_by(|a, b| b.updated_at.cmp(&a.updated_at));
    out
}

fn scan_claude(projects: &[String]) -> Vec<ImportCandidate> {
    let Some(root) = home().map(|h| h.join(".claude").join("projects")) else { return Vec::new() };
    let mut out = Vec::new();
    for project in projects {
        let dir = root.join(claude_encode_path(project));
        let Ok(entries) = fs::read_dir(&dir) else { continue };
        let mut files: Vec<PathBuf> = entries
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|e| e == "jsonl"))
            .collect();
        files.sort_by_key(|p| std::cmp::Reverse(mtime_ms(p)));
        for path in files.into_iter().take(MAX_PER_PROJECT) {
            if let Some(c) = claude_candidate(&path, project) {
                out.push(c);
            }
        }
    }
    out
}

fn claude_candidate(path: &Path, project: &str) -> Option<ImportCandidate> {
    let native_id = path.file_stem()?.to_string_lossy().to_string();
    let mut title: Option<String> = None;
    let mut first_prompt: Option<String> = None;
    let mut has_conversation = false;
    // Titles and the first prompt appear early; don't read the whole file.
    for line in lines_of(path)?.take(400) {
        let Ok(v) = serde_json::from_str::<Value>(&line) else { continue };
        match v.get("type").and_then(Value::as_str) {
            Some("ai-title") => title = title.or_else(|| v.get("aiTitle").and_then(Value::as_str).map(str::to_string)),
            Some("user") if v.get("isSidechain").and_then(Value::as_bool) != Some(true) => {
                has_conversation = true;
                if first_prompt.is_none() {
                    first_prompt = v
                        .get("message")
                        .and_then(|m| m.get("content"))
                        .map(content_texts)
                        .and_then(|t| t.iter().find_map(|s| user_text(s)));
                }
            }
            _ => {}
        }
        if title.is_some() && first_prompt.is_some() {
            break;
        }
    }
    if !has_conversation {
        return None;
    }
    Some(ImportCandidate {
        agent_id: "claude".into(),
        native_id,
        path: path.to_string_lossy().to_string(),
        cwd: project.to_string(),
        title: first_line(&title.or(first_prompt).unwrap_or_else(|| "Claude Code session".into()), 80),
        updated_at: mtime_ms(path),
        size: fs::metadata(path).map(|m| m.len()).unwrap_or(0),
    })
}

fn codex_root() -> Option<PathBuf> {
    std::env::var_os("CODEX_HOME")
        .map(PathBuf::from)
        .or_else(|| home().map(|h| h.join(".codex")))
        .map(|p| p.join("sessions"))
}

fn walk_rollouts(dir: &Path, out: &mut Vec<PathBuf>, depth: usize) {
    if depth > 5 {
        return;
    }
    let Ok(entries) = fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            walk_rollouts(&p, out, depth + 1);
        } else if p.file_name().is_some_and(|n| n.to_string_lossy().starts_with("rollout-")) {
            out.push(p);
        }
    }
}

fn scan_codex(wanted: &HashSet<&str>) -> Vec<ImportCandidate> {
    let Some(root) = codex_root() else { return Vec::new() };
    let mut files = Vec::new();
    walk_rollouts(&root, &mut files, 0);
    files.sort_by_key(|p| std::cmp::Reverse(mtime_ms(p)));

    let mut per_project: HashMap<String, usize> = HashMap::new();
    let mut out = Vec::new();
    for path in files {
        let Some(mut lines) = lines_of(&path) else { continue };
        let Some(first) = lines.next().and_then(|l| serde_json::from_str::<Value>(&l).ok()) else { continue };
        if first.get("type").and_then(Value::as_str) != Some("session_meta") {
            continue;
        }
        let payload = &first["payload"];
        let cwd = payload.get("cwd").and_then(Value::as_str).unwrap_or_default();
        if !wanted.contains(cwd) {
            continue;
        }
        let count = per_project.entry(cwd.to_string()).or_insert(0);
        if *count >= MAX_PER_PROJECT {
            continue;
        }
        let Some(native_id) = payload.get("id").and_then(Value::as_str) else { continue };

        let mut title = None;
        for line in lines.take(600) {
            let Ok(v) = serde_json::from_str::<Value>(&line) else { continue };
            let p = &v["payload"];
            if v.get("type").and_then(Value::as_str) == Some("response_item")
                && p.get("type").and_then(Value::as_str) == Some("message")
                && p.get("role").and_then(Value::as_str) == Some("user")
            {
                title = content_texts(&p["content"]).iter().find_map(|s| user_text(s));
                if title.is_some() {
                    break;
                }
            }
        }
        let Some(title) = title else { continue };
        *count += 1;
        out.push(ImportCandidate {
            agent_id: "codex".into(),
            native_id: native_id.to_string(),
            path: path.to_string_lossy().to_string(),
            cwd: cwd.to_string(),
            title: first_line(&title, 80),
            updated_at: mtime_ms(&path),
            size: fs::metadata(&path).map(|m| m.len()).unwrap_or(0),
        });
    }
    out
}

fn walk_files(dir: &Path, out: &mut Vec<PathBuf>, depth: usize) {
    if depth > 8 { return; }
    let Ok(entries) = fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() { walk_files(&path, out, depth + 1); } else { out.push(path); }
    }
}

fn history_candidate(agent: &str, id: String, path: PathBuf, cwd: &str, updated_at: u64) -> ImportCandidate {
    let size = fs::metadata(&path).map(|m| m.len()).unwrap_or(0);
    ImportCandidate { agent_id: agent.into(), native_id: id, path: path.to_string_lossy().to_string(), cwd: cwd.into(), title: String::new(), updated_at, size }
}

fn cursor_histories(cwd: &str) -> Vec<ImportCandidate> {
    let home = home();
    let data = std::env::var_os("CURSOR_DATA_DIR").map(PathBuf::from).or_else(|| home.clone().map(|p| p.join(".cursor")));
    let config = std::env::var_os("CURSOR_CONFIG_DIR").map(PathBuf::from)
        .or_else(|| std::env::var_os("XDG_CONFIG_HOME").map(|p| PathBuf::from(p).join("cursor")))
        .or_else(|| home.map(|p| p.join(".cursor")));
    let (Some(data), Some(config)) = (data, config) else { return Vec::new() };
    let mut metadata = Vec::new();
    walk_files(&config.join("chats"), &mut metadata, 0);
    let mut transcripts = Vec::new();
    walk_files(&data.join("projects"), &mut transcripts, 0);
    let mut out = Vec::new();
    for meta in metadata.into_iter().filter(|p| p.file_name().is_some_and(|name| name == "meta.json")) {
        let Ok(value) = serde_json::from_str::<Value>(&fs::read_to_string(&meta).unwrap_or_default()) else { continue };
        if value.get("cwd").and_then(Value::as_str) != Some(cwd) { continue; }
        let Some(id) = meta.parent().and_then(Path::file_name).map(|id| id.to_string_lossy().to_string()) else { continue };
        let Some(path) = transcripts.iter().find(|path| path.file_name().is_some_and(|name| name == format!("{id}.jsonl").as_str())) else { continue };
        let updated = value.get("updatedAtMs").and_then(Value::as_u64).unwrap_or_else(|| mtime_ms(path));
        let mut candidate = history_candidate("cursor", id, path.clone(), cwd, updated);
        candidate.title = value.get("title").and_then(Value::as_str).unwrap_or_default().into();
        out.push(candidate);
    }
    out
}

