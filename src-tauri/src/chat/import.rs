//! Import existing CLI sessions (Claude Code, Codex) into FlipFlopper.
//!
//! Scanning only reads the first lines of each file (Codex rollouts can be
//! tens of megabytes); converting streams the file and keeps the most recent
//! entries. The imported session records the CLI's own session id in
//! `native_ids`, so continuing it resumes the real CLI session.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::{HashMap, HashSet};
use std::fs::{self, File};
use std::io::{BufRead, BufReader};
use std::path::{Path, PathBuf};
use uuid::Uuid;

use super::adapters::{new_parser, PermissionMode};
use super::event::{first_line, truncate_output, ChatEvent, ToolKind, TurnStatus, MAX_TOOL_OUTPUT};
use super::store::{self, Entry, SessionMeta};

/// Imported transcripts keep at most this many entries (the newest).
const MAX_ENTRIES: usize = 3000;
/// Candidates listed per project.
const MAX_PER_PROJECT: usize = 200;

#[derive(Debug, Clone, Serialize)]
pub struct ImportCandidate {
    pub agent_id: String,
    pub native_id: String,
    pub path: String,
    pub cwd: String,
    pub title: String,
    pub updated_at: u64,
    pub size: u64,
}

#[derive(Debug, Clone, Deserialize)]
pub struct ImportRequest {
    pub agent_id: String,
    pub native_id: String,
    pub path: String,
    pub cwd: String,
    pub title: String,
    pub updated_at: u64,
}

// ── Helpers ──────────────────────────────────────────────────────────────────

/// `2026-10-22T09:00:00.123Z` → epoch milliseconds. `None` on anything else.
pub(crate) fn parse_iso_ms(s: &str) -> Option<u64> {
    let b = s.as_bytes();
    if b.len() < 19 || b[4] != b'-' || b[7] != b'-' || (b[10] != b'T' && b[10] != b' ') {
        return None;
    }
    let num = |a: usize, z: usize| s.get(a..z)?.parse::<i64>().ok();
    let (y, m, d) = (num(0, 4)?, num(5, 7)?, num(8, 10)?);
    let (h, mi, sec) = (num(11, 13)?, num(14, 16)?, num(17, 19)?);
    let mut ms = 0i64;
    if b.len() > 20 && b[19] == b'.' {
        let digits: String = s[20..].chars().take_while(|c| c.is_ascii_digit()).take(3).collect();
        ms = format!("{digits:0<3}").parse().ok()?;
    }
    let yy = if m <= 2 { y - 1 } else { y };
    let era = (if yy >= 0 { yy } else { yy - 399 }) / 400;
    let yoe = yy - era * 400;
    let doy = (153 * (m + if m > 2 { -3 } else { 9 }) + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    let days = era * 146_097 + doe - 719_468;
    let total = ((days * 24 + h) * 60 + mi) * 60 + sec;
    u64::try_from(total * 1000 + ms).ok()
}

fn mtime_ms(path: &Path) -> u64 {
    fs::metadata(path)
        .and_then(|m| m.modified())
        .ok()
        .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

fn home() -> Option<PathBuf> {
    dirs::home_dir()
}

fn lines_of(path: &Path) -> Option<impl Iterator<Item = String>> {
    let file = File::open(path).ok()?;
    Some(BufReader::new(file).lines().map_while(Result::ok))
}

/// Claude encodes a project path as every non-alphanumeric char → `-`.
fn claude_encode_path(path: &str) -> String {
    path.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '-' }).collect()
}

/// Text of a message `content` (string, or the `text`/`input_text`/`output_text` parts).
fn content_texts(content: &Value) -> Vec<String> {
    match content {
        Value::String(s) => vec![s.clone()],
        Value::Array(parts) => parts
            .iter()
            .filter(|p| matches!(p.get("type").and_then(Value::as_str), Some("text" | "input_text" | "output_text")))
            .filter_map(|p| p.get("text").and_then(Value::as_str).map(str::to_string))
            .collect(),
        _ => Vec::new(),
    }
}

/// Text the CLIs inject into the conversation that the user never typed.
fn is_injected(text: &str) -> bool {
    let t = text.trim_start();
    t.is_empty()
        || t.starts_with("<command-")
        || t.starts_with("<local-command")
        || t.starts_with("<system-reminder>")
        || t.starts_with("<environment_context>")
        || t.starts_with("<user_instructions>")
        || t.starts_with("<permissions")
        || t.starts_with("<user_action>")
        || t.starts_with("# AGENTS.md instructions")
        || t.starts_with("Caveat: The messages below were generated by the user while running local commands")
        || t.starts_with("[Request interrupted by user")
}

/// The user-visible prompt in a message text, if any. Slash commands that
/// carry arguments (`/plan <text>`) become `/plan <text>`; bare commands, their
/// output and injected context yield `None`.
fn user_text(text: &str) -> Option<String> {
    let t = text.trim();
    if let Some(rest) = t.strip_prefix("<command-name>") {
        let (name, rest) = rest.split_once("</command-name>")?;
        let args = rest
            .split_once("<command-args>")
            .and_then(|(_, a)| a.split_once("</command-args>"))
            .map(|(a, _)| a.trim())
            .unwrap_or("");
        return (!args.is_empty()).then(|| format!("{} {}", name.trim(), args));
    }
    (!is_injected(t)).then(|| t.to_string())
}

// ── Scan ─────────────────────────────────────────────────────────────────────

/// Find importable sessions whose working directory is one of `projects`,
/// skipping those whose native id is already attached to an existing session.
pub fn scan(projects: &[String]) -> Vec<ImportCandidate> {
    let wanted: HashSet<&str> = projects.iter().map(String::as_str).collect();
    let already: HashSet<(String, String)> = store::list_sessions()
        .into_iter()
        .flat_map(|s| s.native_ids.into_iter().collect::<Vec<_>>())
        .collect();

    let mut out = Vec::new();
    out.extend(scan_claude(projects));
    out.extend(scan_codex(&wanted));
    out.retain(|c| !already.contains(&(c.agent_id.clone(), c.native_id.clone())));
    out.sort_by(|a, b| b.updated_at.cmp(&a.updated_at));
    out
}

fn scan_claude(projects: &[String]) -> Vec<ImportCandidate> {
    let Some(root) = home().map(|h| h.join(".claude").join("projects")) else { return Vec::new() };
    let mut out = Vec::new();
    for project in projects {
        let dir = root.join(claude_encode_path(project));
        let Ok(entries) = fs::read_dir(&dir) else { continue };
        let mut files: Vec<PathBuf> = entries
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|e| e == "jsonl"))
            .collect();
        files.sort_by_key(|p| std::cmp::Reverse(mtime_ms(p)));
        for path in files.into_iter().take(MAX_PER_PROJECT) {
            if let Some(c) = claude_candidate(&path, project) {
                out.push(c);
            }
        }
    }
    out
}

fn claude_candidate(path: &Path, project: &str) -> Option<ImportCandidate> {
    let native_id = path.file_stem()?.to_string_lossy().to_string();
    let mut title: Option<String> = None;
    let mut first_prompt: Option<String> = None;
    let mut has_conversation = false;
    // Titles and the first prompt appear early; don't read the whole file.
    for line in lines_of(path)?.take(400) {
        let Ok(v) = serde_json::from_str::<Value>(&line) else { continue };
        match v.get("type").and_then(Value::as_str) {
            Some("ai-title") => title = title.or_else(|| v.get("aiTitle").and_then(Value::as_str).map(str::to_string)),
            Some("user") if v.get("isSidechain").and_then(Value::as_bool) != Some(true) => {
                has_conversation = true;
                if first_prompt.is_none() {
                    first_prompt = v
                        .get("message")
                        .and_then(|m| m.get("content"))
                        .map(content_texts)
                        .and_then(|t| t.iter().find_map(|s| user_text(s)));
                }
            }
            _ => {}
        }
        if title.is_some() && first_prompt.is_some() {
            break;
        }
    }
    if !has_conversation {
        return None;
    }
    Some(ImportCandidate {
        agent_id: "claude".into(),
        native_id,
        path: path.to_string_lossy().to_string(),
        cwd: project.to_string(),
        title: first_line(&title.or(first_prompt).unwrap_or_else(|| "Claude Code session".into()), 80),
        updated_at: mtime_ms(path),
        size: fs::metadata(path).map(|m| m.len()).unwrap_or(0),
    })
}

fn codex_root() -> Option<PathBuf> {
    std::env::var_os("CODEX_HOME")
        .map(PathBuf::from)
        .or_else(|| home().map(|h| h.join(".codex")))
        .map(|p| p.join("sessions"))
}

fn walk_rollouts(dir: &Path, out: &mut Vec<PathBuf>, depth: usize) {
    if depth > 5 {
        return;
    }
    let Ok(entries) = fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            walk_rollouts(&p, out, depth + 1);
        } else if p.file_name().is_some_and(|n| n.to_string_lossy().starts_with("rollout-")) {
            out.push(p);
        }
    }
}

fn scan_codex(wanted: &HashSet<&str>) -> Vec<ImportCandidate> {
    let Some(root) = codex_root() else { return Vec::new() };
    let mut files = Vec::new();
    walk_rollouts(&root, &mut files, 0);
    files.sort_by_key(|p| std::cmp::Reverse(mtime_ms(p)));

    let mut per_project: HashMap<String, usize> = HashMap::new();
    let mut out = Vec::new();
    for path in files {
        let Some(mut lines) = lines_of(&path) else { continue };
        let Some(first) = lines.next().and_then(|l| serde_json::from_str::<Value>(&l).ok()) else { continue };
        if first.get("type").and_then(Value::as_str) != Some("session_meta") {
            continue;
        }
        let payload = &first["payload"];
        let cwd = payload.get("cwd").and_then(Value::as_str).unwrap_or_default();
        if !wanted.contains(cwd) {
            continue;
        }
        let count = per_project.entry(cwd.to_string()).or_insert(0);
        if *count >= MAX_PER_PROJECT {
            continue;
        }
        let Some(native_id) = payload.get("id").and_then(Value::as_str) else { continue };

        let mut title = None;
        for line in lines.take(600) {
            let Ok(v) = serde_json::from_str::<Value>(&line) else { continue };
            let p = &v["payload"];
            if v.get("type").and_then(Value::as_str) == Some("response_item")
                && p.get("type").and_then(Value::as_str) == Some("message")
                && p.get("role").and_then(Value::as_str) == Some("user")
            {
                title = content_texts(&p["content"]).iter().find_map(|s| user_text(s));
                if title.is_some() {
                    break;
                }
            }
        }
        let Some(title) = title else { continue };
        *count += 1;
        out.push(ImportCandidate {
            agent_id: "codex".into(),
            native_id: native_id.to_string(),
            path: path.to_string_lossy().to_string(),
            cwd: cwd.to_string(),
            title: first_line(&title, 80),
            updated_at: mtime_ms(&path),
            size: fs::metadata(&path).map(|m| m.len()).unwrap_or(0),
        });
    }
    out
}

// ── Convert ──────────────────────────────────────────────────────────────────

/// Builds a transcript, opening a turn at the first agent output after a user
/// prompt and closing it before the next prompt.
struct Builder {
    agent: String,
    entries: Vec<Entry>,
    turn: Option<String>,
    first_ts: u64,
    last_ts: u64,
}

impl Builder {
    fn new(agent: &str) -> Self {
        Self { agent: agent.into(), entries: Vec::new(), turn: None, first_ts: 0, last_ts: 0 }
    }

    fn touch(&mut self, ts: u64) -> u64 {
        if ts > 0 {
            if self.first_ts == 0 {
                self.first_ts = ts;
            }
            self.last_ts = self.last_ts.max(ts);
        }
        if ts > 0 { ts } else { self.last_ts }
    }

    fn close(&mut self, ts: u64) {
        if let Some(turn_id) = self.turn.take() {
            self.entries.push(Entry::Event {
                event: ChatEvent::TurnEnded { turn_id, status: TurnStatus::Done, changed_files: vec![] },
                ts,
            });
        }
        self.trim_completed();
    }

    /// Discard oldest completed turns as conversion proceeds. Never drain the
    /// only retained turn, even when that final turn exceeds the entry budget.
    fn trim_completed(&mut self) {
        while self.entries.len() > MAX_ENTRIES {
            let mut cut = self.entries.len() - MAX_ENTRIES;
            while cut < self.entries.len() && !matches!(self.entries[cut], Entry::User { .. }) {
                cut += 1;
            }
            if cut == self.entries.len() {
                break;
            }
            self.entries.drain(..cut);
        }
    }

    fn user(&mut self, text: String, ts: u64) {
        let ts = self.touch(ts);
        self.close(ts);
        self.entries.push(Entry::User { text, agent_id: self.agent.clone(), ts, attachments: vec![] });
        // A previously oversized completed turn is no longer the final turn.
        self.trim_completed();
    }

    fn event(&mut self, event: ChatEvent, ts: u64) {
        let ts = self.touch(ts);
        if self.turn.is_none() {
            let id = Uuid::new_v4().to_string();
            self.entries.push(Entry::Event {
                event: ChatEvent::TurnStarted { turn_id: id.clone(), agent_id: self.agent.clone() },
                ts,
            });
            self.turn = Some(id);
        }
        // Resume ids and models are tracked on the session, not in the transcript.
        if !matches!(event, ChatEvent::NativeSession { .. }) {
            self.entries.push(Entry::Event { event, ts });
        }
    }

    fn finish(mut self) -> (Vec<Entry>, u64, u64) {
        let ts = self.last_ts;
        self.close(ts);
        (self.entries, self.first_ts, self.last_ts)
    }
}

fn convert_claude(path: &Path) -> Option<(Vec<Entry>, u64, u64)> {
    let mut b = Builder::new("claude");
    let mut parser = new_parser("claude");
    for line in lines_of(path)? {
        let Ok(v) = serde_json::from_str::<Value>(&line) else { continue };
        if v.get("isSidechain").and_then(Value::as_bool) == Some(true) || v.get("isMeta").and_then(Value::as_bool) == Some(true) {
            continue;
        }
        let ts = v.get("timestamp").and_then(Value::as_str).and_then(parse_iso_ms).unwrap_or(0);
        match v.get("type").and_then(Value::as_str) {
            Some("user") => {
                let content = v.get("message").and_then(|m| m.get("content")).cloned().unwrap_or(Value::Null);
                let has_results = content
                    .as_array()
                    .is_some_and(|a| a.iter().any(|p| p.get("type").and_then(Value::as_str) == Some("tool_result")));
                if has_results {
                    for ev in parser.parse_line(&line) {
                        b.event(ev, ts);
                    }
                } else {
                    let text = content_texts(&content).iter().filter_map(|t| user_text(t)).collect::<Vec<_>>().join("\n");
                    if !text.trim().is_empty() {
                        b.user(text.trim().to_string(), ts);
                    }
                }
            }
            Some("assistant") => {
                for ev in parser.parse_line(&line) {
                    b.event(ev, ts);
                }
            }
            _ => {}
        }
    }
    let (entries, first, last) = b.finish();
    (!entries.is_empty()).then_some((entries, first, last))
}

fn codex_kind(name: &str) -> ToolKind {
    let n = name.to_ascii_lowercase();
    if n.contains("shell") || n.contains("exec") || n.contains("bash") {
        ToolKind::Bash
    } else if n.contains("patch") || n.contains("edit") || n.contains("write") {
        ToolKind::Edit
    } else if n.contains("plan") || n.contains("todo") {
        ToolKind::Todo
    } else if n.contains("search") || n.contains("web") {
        ToolKind::Web
    } else {
        ToolKind::Other
    }
}

/// A short target for a Codex tool call: `cmd`/`command` (string or argv), path or query.
fn codex_title(name: &str, args: &Value) -> String {
    for key in ["cmd", "command", "path", "query", "url"] {
        match args.get(key) {
            Some(Value::String(s)) if !s.is_empty() => return first_line(s, 160),
            Some(Value::Array(a)) if !a.is_empty() => {
                let joined = a.iter().filter_map(Value::as_str).collect::<Vec<_>>().join(" ");
                if !joined.is_empty() {
                    return first_line(&joined, 160);
                }
            }
            _ => {}
        }
    }
    name.to_string()
}

fn output_text(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Array(parts) => parts.iter().filter_map(|p| p.get("text").and_then(Value::as_str)).collect::<Vec<_>>().join("\n"),
        Value::Null => String::new(),
        other => other.to_string(),
    }
}

fn convert_codex(path: &Path) -> Option<(Vec<Entry>, u64, u64)> {
    let mut b = Builder::new("codex");
    for line in lines_of(path)? {
        let Ok(v) = serde_json::from_str::<Value>(&line) else { continue };
        if v.get("type").and_then(Value::as_str) != Some("response_item") {
            continue;
        }
        let ts = v.get("timestamp").and_then(Value::as_str).and_then(parse_iso_ms).unwrap_or(0);
        let p = &v["payload"];
        match p.get("type").and_then(Value::as_str) {
            Some("message") => match p.get("role").and_then(Value::as_str) {
                Some("user") => {
                    let text = content_texts(&p["content"]).iter().filter_map(|t| user_text(t)).collect::<Vec<_>>().join("\n");
                    if !text.trim().is_empty() {
                        b.user(text.trim().to_string(), ts);
                    }
                }
                Some("assistant") => {
                    let text = content_texts(&p["content"]).join("\n");
                    if !text.trim().is_empty() {
                        b.event(ChatEvent::Text { delta: text }, ts);
                    }
                }
                _ => {}
            },
            Some("function_call") | Some("custom_tool_call") | Some("local_shell_call") => {
                let name = p.get("name").and_then(Value::as_str).unwrap_or("shell");
                // `arguments` is a JSON string; custom tools carry raw `input`; shell calls an `action`.
                let args: Value = p
                    .get("arguments")
                    .and_then(Value::as_str)
                    .and_then(|s| serde_json::from_str(s).ok())
                    .or_else(|| p.get("action").cloned())
                    .or_else(|| p.get("input").map(|i| serde_json::json!({ "cmd": i })))
                    .unwrap_or(Value::Null);
                let id = p.get("call_id").or_else(|| p.get("id")).and_then(Value::as_str).unwrap_or_default().to_string();
                b.event(
                    ChatEvent::ToolCall { id, kind: codex_kind(name), title: codex_title(name, &args), input: args },
                    ts,
                );
            }
            Some("function_call_output") | Some("custom_tool_call_output") => {
                let id = p.get("call_id").and_then(Value::as_str).unwrap_or_default().to_string();
                b.event(
                    ChatEvent::ToolResult { id, ok: true, output: truncate_output(output_text(&p["output"]), MAX_TOOL_OUTPUT) },
                    ts,
                );
            }
            _ => {}
        }
    }
    let (entries, first, last) = b.finish();
    (!entries.is_empty()).then_some((entries, first, last))
}

